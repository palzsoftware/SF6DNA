// Ignore object property order only. Preserve every field, string and array order.
function sameDetail(left: DailyTrainingDetail, right: DailyTrainingDetail): boolean {
  const keys = Object.keys(left) as (keyof DailyTrainingDetail)[];
  if (keys.length !== Object.keys(right).length) return false;
  return keys.every((key) => {
    if (!Object.prototype.hasOwnProperty.call(right, key)) return false;
    const expected = left[key];
    const actual = right[key];
    return Array.isArray(expected)
      ? Array.isArray(actual) && expected.length === actual.length &&
        expected.every((value, index) => value === actual[index])
      : expected === actual;
  });
}

// A restored snapshot receives guides only when its complete content matches.
export function getQualityGuide(detail: DailyTrainingDetail) {
  for (const key of Object.keys(QUALITY_GUIDES) as (keyof typeof QUALITY_GUIDES)[]) {
    if (sameDetail(DAILY_TRAINING_DETAILS[key], detail)) return QUALITY_GUIDES[key];
  }
  return null;
}
